def _metric_records():
    """Uneven pockets, invalid groups, raw SMILES aliases, stereo, and duplicates."""
    cases = [
        ("p1", "CC", "CCO", ["CCO"] * 60 + ["OCC"] * 20 + ["CCN"] * 10 + [""] * 10),
        ("p1", "N", "CN", ["N"] * 100),
        ("p2", "C", "CC", ["CC"] * 100),
        ("p2", "O", "CO", ["CCO"] * 100),
        ("p3", "CC", "C[C@H](O)F", ["C[C@@H](O)F"] * 100),
        ("p3", "C(C)", "CCCO", ["CCCO"] * 100),
        ("p4", "C", "CC", [""] * 100),
        # Two benchmark instances sharing a protein/scaffold still divide by 100.
        ("p2", "C", "CCO", ["CCO"] * 100),
    ]
    return [
        dict(
            protein_filename=protein,
            scaffold=scaffold,
            true_molecule=true,
            pred_molecule=pred,
            pred_rgroup="",
        )
        for protein, scaffold, true, preds in cases
        for pred in preds
    ]


def test_metrics_match_released_diffdec_golden_values():
    # Generated by the unmodified upstream compute_metrics.py at revision
    # 916ae14207b2783a90336bb8509374535c5791f9 (same RDKit). Do not regenerate
    # from this implementation: this fixture protects the upstream conventions.
    rows = _metric_records()
    before = copy.deepcopy(rows)
    result = compute_diffdec_metrics(rows)
    assert result == pytest.approx(
        {
            "validity": 61.25,
            "uniqueness": 1.8333333333333333,
            "similarity": 0.8962962962962964,
            "recovery": 50.0,
        }
    )
    assert rows == before


@pytest.mark.parametrize(
    ("pred", "scaffold", "valid"),
    [
        ("", "CC", False),
        ("CC", "CC", False),
        ("not-a-smiles", "CC", False),
        ("CC.O", "CC", True),
        ("C(C)(C)(C)(C)C", "C", True),
        ("C(C)", "CC", True),  # Upstream tests textual equality, not graph equality.
        ("CO", "CC", False),
    ],
)
def test_diffdec_validity_preserves_permissive_upstream_rules(pred, scaffold, valid):
    assert diffdec_is_valid(pred, scaffold) is valid


def test_recovery_removes_stereo_and_hydrogens():
    assert diffdec_recovery_smiles("C[C@H](O)F") == diffdec_recovery_smiles(
        "C[C@@H](O)F"
    )
    assert diffdec_recovery_smiles("[H]OC") == "CO"


def test_empty_and_all_invalid_populations_are_explicit():
    with pytest.raises(ValueError, match="at least one attempt"):
        compute_diffdec_metrics([])
    result = compute_diffdec_metrics(
        [
            dict(
                scaffold="CC",
                true_molecule="CCO",
                pred_molecule="",
                protein_filename="p",
            )
        ]
    )
    assert result["validity"] == result["recovery"] == 0
    assert math.isnan(result["uniqueness"])
    assert math.isnan(result["similarity"])


def test_metric_file_roundtrip_preserves_empty_fields_and_raw_smiles(tmp_path):
    path = tmp_path / "metric.smi"
    records = _metric_records()
    write_diffdec_records(records, path)
    assert read_diffdec_records(path) == records
    path.write_text("CC CCO  p.pdb\nCC CCO OCC p.pdb\n")
    assert [r["pred_molecule"] for r in read_diffdec_records(path)] == ["", "OCC"]
    path.write_text("CC CCO\n")
    with pytest.raises(ValueError, match="expected DiffDec metric fields"):
        read_diffdec_records(path)


def test_score_cli_writes_roundtrippable_records_and_json(tmp_path):
    records = _metric_records()
    path, output = tmp_path / "metric.smi", tmp_path / "results"
    write_diffdec_records(records, path)
    runpy.run_path(str(SCRIPT))["main"](
        ["--metrics-file", str(path), "--output-dir", str(output)]
    )
    report = json.loads((output / "metrics.json").read_text())
    assert report["metrics"] == compute_diffdec_metrics(records)
    assert report["n_attempts"] == 800
    assert report["notes"]  # Duplicate conditions are still merged and /100.
    assert report["docking"]["status"] == "not_run"
    assert read_diffdec_records(output / "crossdock_test_metric.smi") == records


def _published_fixture(base, condition):
    """Put ligand atoms out of order; include a pocket atom and a fake R-group atom."""
    raw = base.get(condition["base_idx"])
    metadata = base.get_metadata(condition["base_idx"])
    pocket = base.get_raw_pocket(condition["base_idx"])
    pocket_position = torch.as_tensor(pocket["pos"][0]) + metadata["lig_center"]
    pocket_z = Chem.GetPeriodicTable().GetAtomicNumber(str(pocket["elem"][0]))
    positions = raw.pos + metadata["lig_center"]
    order = torch.arange(len(raw.z) - 1, -1, -1)
    scaffold = torch.zeros(len(raw.z), dtype=torch.bool)
    scaffold[condition["atom_indices"]] = True
    entries, table = [], []
    for uuid in ("10", "11"):
        entries.append(
            {
                "uuid": uuid,
                "name": metadata["smiles"],
                "positions": torch.cat(
                    [positions[order], pocket_position[None], torch.zeros(1, 3)]
                ),
                "charges": torch.cat([raw.z[order], torch.tensor([pocket_z, 0])]),
                "scaffold_only_mask": torch.cat(
                    [scaffold[order], torch.tensor([False, False])]
                ),
                "rgroup_mask": torch.cat(
                    [~scaffold[order], torch.tensor([False, True])]
                ),
                "pocket_mask": torch.cat(
                    [
                        torch.zeros(len(raw.z), dtype=torch.bool),
                        torch.tensor([True, False]),
                    ]
                ),
            }
        )
        table.append(
            dict(
                uuid=uuid,
                molecule=metadata["smiles"],
                scaffold=condition["scaffold"],
                protein_filename="data/crossdocked_pocket10/" + metadata["pocket_fn"],
            )
        )
    return entries, table


def test_published_conditions_match_pose_and_keep_duplicate_instances(
    pocket_scaffolds, tmp_path
):
    base = _tokenized(pocket_scaffolds, split="test")
    try:
        wrapped = ScaffoldPocketWrapper(
            **_scaffold_options(base, tmp_path, stage="test", enumerate_slicings=True)
        )
        cached = cached_cut_conditions(wrapped)
        entries, table = _published_fixture(base, cached[0])
        conditions = published_cut_conditions(base, entries, table)
        assert len(conditions) == 2
        assert conditions[0]["atom_indices"] == cached[0]["atom_indices"]
        assert conditions[0]["atom_indices"] == conditions[1]["atom_indices"]
        no_table = published_cut_conditions(base, entries)
        assert [c["atom_indices"] for c in no_table] == [
            c["atom_indices"] for c in conditions
        ]
        assert conditions[0]["protein_filename"] == table[0]["protein_filename"]
        wrong_pocket = copy.deepcopy(entries)
        wrong_pocket[0]["positions"][-2] += 1
        with pytest.raises(ValueError, match="found 0"):
            published_cut_conditions(base, wrong_pocket)
        dataset = DiffDecPocketEvaluationDataset(base, conditions)
        assert len(dataset) == 200
        first, target = dataset[0]
        last, _ = dataset[199]
        torch.testing.assert_close(first.x, last.x)
        torch.testing.assert_close(first.contexts["pocket"].x, base.get_pocket(0).x)
        torch.testing.assert_close(target.x, base[0].x)
        with pytest.raises(IndexError):
            dataset[200]
        batch = pocket_eval_collate_fn([dataset[0], dataset[100]])
        assert batch[0].contexts["pocket"].num_graphs == 2
        entries[0]["positions"] += 1
        with pytest.raises(ValueError, match="found 0"):
            published_cut_conditions(base, entries, table)
    finally:
        base.close()


def _sampling_config(tmp_path, root, monkeypatch):
    assets = _pretrained_assets(tmp_path / "assets")
    monkeypatch.setenv("PROJECT_ROOT", str(tmp_path))
    monkeypatch.setenv("MORPH_PRETRAINED_ASSETS", str(assets))
    monkeypatch.setenv("MORPH_PRETRAINED_CKPT", "/missing/pretrained.ckpt")
    with initialize_config_dir(
        config_dir=str(SCRIPT.parents[1] / "configs"), version_base="1.1"
    ):
        cfg = compose(
            config_name="default",
            overrides=[
                "defaults=crossdocked/scaffold_decoration",
                f"data.root={root}",
                "data.val_fraction=0.25",
                "data.scaffold_kind=rgroup",
                "data.preprocess_workers=0",
                "model.backbone.d_model=32",
                "model.backbone.num_layers=1",
                "model.backbone.nhead=4",
                "model.backbone.out_node_nf=16",
                "model.backbone.out_edge_nf=16",
                "model.backbone.ffn_multiple_of=8",
                "model.backbone.ctx_dim=16",
                "model.head_node_adapter_dim=16",
                "model.head_edge_adapter_dim=16",
                "model.head_insertion_adapter_dim=16",
                "model.head_insertion_edge_dim=16",
                "model.pocket_encoder.nhead=4",
                "model.pocket_encoder.num_attn_layers=1",
            ],
        )
    config_path = tmp_path / "config.yaml"
    # Save before configure_model, as Hydra does for real training runs.
    OmegaConf.save(cfg, config_path)
    pre = hydra.utils.instantiate(cfg.data.preprocessing)
    data = prepare_model_data(cfg, pre.vocab, pre.distributions)
    dm = hydra.utils.instantiate(
        cfg.data.datamodule,
        _recursive_=False,
        vocab=data.vocab,
        distributions=data.prior,
        noise_distributions=data.empirical,
        eval_panel=None,
        enumerate_slicings=True,
    )
    dm.setup("test")
    dm.configure_model(cfg)
    cfg.model.module.pretrained_ckpt = None
    module = build_model_module(cfg, data).eval()
    checkpoint = tmp_path / "model.ckpt"
    torch.save({"state_dict": module.state_dict()}, checkpoint)
    return config_path, checkpoint, dm.test_datasets[0]


@pytest.mark.parametrize("protocol", ["cached", "published", "published_table"])
def test_checkpoint_sampling_cli_uses_fixed_cuts_and_every_attempt(
    pocket_scaffolds, tmp_path, monkeypatch, protocol
):
    config, checkpoint, wrapped = _sampling_config(
        tmp_path, pocket_scaffolds, monkeypatch
    )
    base = wrapped.base_dataset
    try:
        condition = cached_cut_conditions(wrapped)[0]
        entries, table = _published_fixture(base, condition)
        tensor_path, table_path = tmp_path / "official.pt", tmp_path / "official.csv"
        torch.save(entries, tensor_path)
        with table_path.open("w") as handle:
            writer = csv.DictWriter(handle, fieldnames=table[0].keys())
            writer.writeheader()
            writer.writerows(table)
        output = tmp_path / "evaluation"
        # Exercise real checkpoint loading and the actual two-step sampler on CPU.
        mode_args = (
            ["--cached-cuts"]
            if protocol == "cached"
            else ["--diffdec-data", str(tensor_path)]
        )
        if protocol == "published_table":
            mode_args += ["--diffdec-table", str(table_path)]
        script = runpy.run_path(str(SCRIPT))
        format_prediction = script["_format_prediction"]
        expected_pocket = (
            base.get_pocket(condition["base_idx"]).x * base.distributions.coordinate_std
            + base.get_metadata(condition["base_idx"])["lig_center"]
        )

        def check_receptor_frame(graph, vocab):
            torch.testing.assert_close(
                graph.contexts["pocket"].x, expected_pocket, atol=1e-4, rtol=1e-5
            )
            return format_prediction(graph, vocab)

        monkeypatch.setitem(
            script["main"].__globals__, "_format_prediction", check_receptor_frame
        )
        script["main"](
            [
                "--checkpoint",
                str(checkpoint),
                "--config",
                str(config),
                *mode_args,
                "--output-dir",
                str(output),
                "--device",
                "cpu",
                "--steps",
                "2",
                "--batch-size",
                "13",
                "--limit-conditions",
                "1",
            ]
        )
        rows = read_diffdec_records(output / "crossdock_test_metric.smi")
        attempts = [
            json.loads(line)
            for line in (output / "attempts.jsonl").read_text().splitlines()
        ]
        report = json.loads((output / "metrics.json").read_text())
        assert len(rows) == len(attempts) == report["n_attempts"] == 100
        assert [row["sample_id"] for row in attempts] == list(range(100))
        assert report["provenance"]["condition_source"] == (
            "morph_cached_cuts" if protocol == "cached" else "published_diffdec"
        )
        if protocol != "cached":
            assert report["provenance"]["available_condition_count"] == 2
        saved = OmegaConf.load(output / "config.yaml")
        assert saved.model.module.integrator.num_integration_steps == 2
        assert saved.data.pocket_vocab is not None
    finally:
        base.close()
